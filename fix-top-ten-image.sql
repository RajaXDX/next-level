--
-- المشكلة: المسار المحفوظ كان `assets/icon-180` — بلا امتداد، ولملف
-- يعيش في مستودع توب تن لا في هذا المستودع. فكان الطلب يرجع 404
-- والبطاقة تعرض صورة مكسورة (لا الإيموجي، لأن `image` ليست فارغة).
--
-- ⚠️ **البطاقة المعروضة تأتي من قاعدة البيانات لا من `js/config.js`** —
-- ما في config.js نسخة احتياطية فقط. شغّل هذا، أو عدّل حقل «الصورة
-- (مسار)» من لوحة الإدارة إلى `assets/top-ten.png` — كلاهما يؤدّي الغرض.
--
-- ويلزم قبله أن يكون `assets/top-ten.png` مرفوعاً إلى المستودع.

UPDATE projects SET image = 'assets/top-ten.png' WHERE name = 'توب تن';

SELECT name, image FROM projects ORDER BY sort_order;
